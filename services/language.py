"""Определение языка сообщения клиента.

Нужно для служебных ответов бота («передаю вопрос…», «уточняю…»): их
не генерирует модель, поэтому переводчиком быть некомому — выбираем
шаблон по языку сообщения, на которое бот отвечает.
"""

import re

# Казахские буквы, которых нет в русском (с учётом регистра).
KZ_LETTERS = re.compile(r"[әғқңөұүһі]", re.IGNORECASE)
# Слова-маркеры казахского.
KZ_WORDS = re.compile(
    r"\b(барма|және|қалай|қалайсыз|біз|сіз|керек|расталады|жазылу|жазылуға|"
    r"ертең|үшін|туралы|жоқ|рақмет|жақсы|болса|болады|құтты|қайырлы|сәлем|"
    r"мерекесі|қанша|бересіз|береміз|жазыңыз|айтыңыз|тұрады|тұра|кешке|"
    r"таңертең|дүйсенбі|сенбі|жұма)\b",
    re.IGNORECASE)
# Служебные слова русского для сравнения «весов» в смешанных сообщениях.
RU_WORDS = re.compile(
    r"\b(и|в|на|с|вы|мы|не|что|как|когда|можно|вам|вас|для|по|это|если|но|или|"
    r"спасибо|пожалуйста|хочу|сколько|стоит|работаете|записаться|сегодня|"
    r"завтра|утро|вечер|нельзя|надо|давайте)\b",
    re.IGNORECASE)
# Вопросительная частица латинской казахской речи («Парковка барма платный?»):
# однозначный признак, даже если остальное сообщение русское.
STRONG_KZ = re.compile(r"\bбарма\b", re.IGNORECASE)
# Кавычки: «…» “…” "…" — содержимое не считаем признаком языка сообщения.
QUOTED = re.compile(r"[«“\"][^»”\"]*[»”\"]")


def detect_language(text: str) -> str:
    """Возвращает "kk" для казахского сообщения, иначе "ru".

    Эвристика сознательно простая: «барма» сразу считаем казахским, иначе
    сравниваем число казахских маркеров/букв с числом русских служебных
    слов (в смешанных приветствиях вида «Сәлем, сколько стоит…» побеждает
    более длинная часть). Слова в кавычках игнорируются: «Скажите
    “рақмет”» — это русский вопрос про казахское слово.
    """
    if not text:
        return "ru"
    stripped = QUOTED.sub(" ", text)
    if STRONG_KZ.search(stripped):
        return "kk"
    kz_score = len(KZ_WORDS.findall(stripped)) + len(KZ_LETTERS.findall(stripped))
    ru_score = len(RU_WORDS.findall(stripped))
    return "kk" if kz_score > ru_score else "ru"
